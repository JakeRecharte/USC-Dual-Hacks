// Regenerates src/lib/household-sites.ts from public/buildings.json.
//
//   node scripts/build-household-sites.mjs
//
// Every building footprint OpenStreetMap knows about inside the perimeter becomes a tracked
// household. The previous list held 1,999 of the 8,103, described in its own header as
// "dwelling footprints" — but the footprint areas say otherwise: tracked and untracked had
// the same size distribution (median 242 m² against 245 m²), and 3,113 untracked buildings
// were larger than the median tracked one. It was a quarter of the buildings picked
// arbitrarily, not garages being filtered out, and it left the officer map three-quarters
// empty with no way to tell why.
//
// This script exists so the next person does not have to measure footprints to find that
// out. The output is generated; edit this, not it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');

const buildings = JSON.parse(readFileSync(resolve(web, 'public/buildings.json'), 'utf8'));

// Read ZONE_ORDER out of zones.ts rather than restating it: the index written into each
// site is an index into that array, and a silent drift here would mis-zone every household.
const zonesSrc = readFileSync(resolve(web, 'src/lib/zones.ts'), 'utf8');
const orderMatch = zonesSrc.match(/export const ZONE_ORDER = \[([\s\S]*?)\] as const;/);
if (!orderMatch) throw new Error('could not find ZONE_ORDER in src/lib/zones.ts');
const ZONE_ORDER = [...orderMatch[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);

const indexOfZone = new Map(ZONE_ORDER.map((z, i) => [z, i]));
for (const name of buildings.zones) {
  if (!indexOfZone.has(name)) throw new Error(`buildings.json zone ${name} is not in ZONE_ORDER`);
}

const sites = buildings.cent.map(([lat, lng], i) => {
  const zoneName = buildings.zones[buildings.zone[i]];
  const zoneIndex = indexOfZone.get(zoneName);
  if (zoneIndex === undefined) throw new Error(`building ${i} has no zone`);
  // Centroids are already rounded to 5dp in the file, and public/buildings.json is keyed on
  // that rounding, so the map can find each household's outline. Do not re-round here.
  return [lat, lng, zoneIndex];
});

const body = sites.map(([lat, lng, z]) => `[${lat},${lng},${z}]`).join(',');

const out = `// Generated by scripts/build-household-sites.mjs. Do not edit by hand.
//
// Centroid and zone of every tracked household: all ${sites.length.toLocaleString('en-US')} building footprints
// OpenStreetMap has inside the perimeter. The matching outlines live in
// public/buildings.json, keyed by the same rounded centroid, so the map draws the actual
// shape of each house rather than a pin.
//
// Zones are k-means clusters over the real building centroids, then named after the
// district each one sits in, so a zone follows where houses actually are instead of a
// guessed circle. The third number indexes ZONE_ORDER in zones.ts.
//
// A .ts module rather than .json: Node's ESM loader needs an import attribute for JSON and
// the bundler does not, so this keeps the tests and the app loading it the same way. It is
// imported only by addresses.ts, which is server-side, so its size costs the browser
// nothing.
//
// [latitude, longitude, zone index into ZONE_ORDER]
export const HOUSEHOLD_SITES: [number, number, number][] = [${body}];
`;

writeFileSync(resolve(web, 'src/lib/household-sites.ts'), out);
console.log(`wrote ${sites.length} household sites to src/lib/household-sites.ts`);
