// Writes src/lib/scenario/street-threat.ts from docs/research/street-threat.json.
//   node scripts/build-street-threat.mjs
//
// The scenario needs each street's fire threat even when the board is not reading it from
// Supabase (memory mode, or a project where `npm run apply-threat` has not run). The research
// file lives outside web/, which the bundler will not reach, and Node's ESM loader wants an
// import attribute for JSON, so the same rows are written out as a .ts module. The test
// (test/scenario.test.ts) fails if this file and the research file disagree.
import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../../docs/research/street-threat.json', import.meta.url);
const target = new URL('../src/lib/scenario/street-threat.ts', import.meta.url);

const LEVELS = new Set(['extreme', 'high', 'moderate', 'low']);
const rows = JSON.parse(await readFile(source, 'utf8'))
  .filter((r) => LEVELS.has(r.fire_threat_level))
  .map((r) => ({
    street: String(r.street),
    zone_id: String(r.zone_id),
    level: r.fire_threat_level,
    reason: String(r.reason ?? ''),
    source: String(r.source ?? ''),
  }));

const body = `// Generated by scripts/build-street-threat.mjs from docs/research/street-threat.json.
// Do not edit by hand: change the research file and run the script again.
//
// Per-street fire threat from the 2025 Palisades Fire research (extreme / high / moderate / low),
// with the reason and source for each. houses.fire_threat_level in Supabase holds the same
// levels; the scenario prefers that and falls back to this table.
import type { ThreatLevel } from '../types';

export interface StreetThreat {
  street: string;
  zone_id: string;
  level: ThreatLevel;
  reason: string;
  source: string;
}

export const STREET_THREAT: StreetThreat[] = ${JSON.stringify(rows, null, 2)};
`;

await writeFile(target, body);
console.log(`wrote ${rows.length} streets to src/lib/scenario/street-threat.ts`);
